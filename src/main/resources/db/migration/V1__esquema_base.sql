create table amenities (
    id bigint generated by default as identity,
    category varchar(30) not null check (category in ('COMFORT','WELLNESS','ENTERTAINMENT','WORK','FOOD','TRANSPORT')),
    icon varchar(60),
    name varchar(100) not null unique,
    primary key (id)
);

create table availability (
    availability_date date not null,
    id bigint generated by default as identity,
    room_id bigint not null,
    status varchar(20) not null check (status in ('AVAILABLE','BLOCKED','BOOKED')),
    primary key (id),
    unique (room_id, availability_date)
);

create table bookings (
    check_in date not null,
    check_out date not null,
    guests integer not null,
    total_amount numeric(12,2) not null,
    cancelled_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    guest_id bigint not null,
    id bigint generated by default as identity,
    room_id bigint not null,
    code varchar(20) not null unique,
    status varchar(20) not null check (status in ('PENDING_PAYMENT','CONFIRMED','CANCELLED')),
    primary key (id)
);

create table hotels (
    active boolean not null,
    latitude float(53),
    longitude float(53),
    sustainability_seal boolean not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    city varchar(100) not null,
    district varchar(100),
    legal_name varchar(150) not null,
    trade_name varchar(150) not null,
    address varchar(250) not null,
    sustainability_description varchar(1000),
    primary key (id)
);

create table rates (
    end_date date not null,
    price numeric(10,2) not null,
    start_date date not null,
    id bigint generated by default as identity,
    room_id bigint not null,
    name varchar(100) not null,
    primary key (id)
);

create table recommendations (
    compatibility integer not null,
    ranking_position integer not null,
    id bigint generated by default as identity,
    profile_id bigint not null,
    room_id bigint not null,
    explanation varchar(1000),
    primary key (id)
);

create table room_amenities (
    amenity_id bigint not null,
    id bigint generated by default as identity,
    room_id bigint not null,
    detail varchar(200),
    primary key (id),
    unique (room_id, amenity_id)
);

create table rooms (
    base_price numeric(10,2) not null,
    capacity integer not null,
    floor_number integer not null,
    privacy_score integer not null,
    quiet_score integer not null,
    space_score integer not null,
    view_score integer not null,
    created_at timestamp(6) with time zone not null,
    hotel_id bigint not null,
    id bigint generated by default as identity,
    bed_type varchar(20) not null check (bed_type in ('SINGLE','TWIN','DOUBLE','QUEEN','KING')),
    room_number varchar(20) not null,
    status varchar(20) not null check (status in ('ACTIVE','INACTIVE','DELETED')),
    room_type varchar(30) not null check (room_type in ('STANDARD','SUPERIOR','DELUXE','SUITE','EXECUTIVE_SUITE')),
    name varchar(120) not null,
    description varchar(500),
    image_url varchar(500),
    primary key (id)
);

create table travel_profile_amenities (
    amenity_id bigint,
    profile_id bigint not null
);

create table travel_profile_priorities (
    profile_id bigint not null,
    priority varchar(20) check (priority in ('PRIVACY','PRICE','COMFORT','SPACE','QUIET','VIEW','ENTERTAINMENT','WORK','LUXURY'))
);

create table travel_profiles (
    check_in date not null,
    check_out date not null,
    guests integer not null,
    max_budget_per_night numeric(10,2) not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    purpose varchar(20) not null check (purpose in ('BUSINESS','TOURISM','COUPLE','FAMILY','EVENT','REST','OTHER')),
    city varchar(100),
    free_text varchar(500),
    primary key (id)
);

create table users (
    active boolean not null,
    created_at timestamp(6) with time zone not null,
    hotel_id bigint,
    id bigint generated by default as identity,
    role varchar(20) not null check (role in ('GUEST','ADMIN')),
    password_hash varchar(100) not null,
    name varchar(120) not null,
    email varchar(180) not null unique,
    primary key (id)
);

